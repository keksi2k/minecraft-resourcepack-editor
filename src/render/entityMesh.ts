/** Baked vanilla geometry, generated by scripts/DumpEntityModels.java. */
interface PartJson {
  /** x, y, z, xRot, yRot, zRot, xScale, yScale, zScale (pixels / radians) */
  pose: number[];
  visible: boolean;
  /** cubes → polygons → 4 vertices × (x, y, z, u, v), u/v normalised to the layer's texture size. */
  cubes: number[][][];
  children: Record<string, PartJson>;
}

interface LayerJson {
  tex: [number, number];
  root: PartJson;
}

export const ENTITY_MODELS = models as unknown as Record<string, LayerJson>;

type Vec3 = [number, number, number];

/** How a mob differs from its model's default: posed and hidden parts. */
type MobLook = Pick<MobDef, 'pose' | 'hidden'>;

interface PolygonVisit {
  part: string;
  /** Vertices in entity model space (pixels, y down). */
  verts: Vec3[];
  uvs: [number, number][];
  /** Outward normal in model space. */
  normal: THREE.Vector3;
}

function walk(
  part: PartJson,
  parent: THREE.Matrix4,
  name: string,
  look: MobLook | undefined,
  visit: (p: PolygonVisit) => void,
) {
  const own = name.split('/').pop()!;
  if (!part.visible || look?.hidden?.includes(own)) return;
  const [x, y, z, xr, yr, zr, xs, ys, zs] = part.pose;
  const extra = look?.pose?.[own] ?? [0, 0, 0];
  const m = parent
    .clone()
    .multiply(new THREE.Matrix4().makeTranslation(x, y, z))
    .multiply(new THREE.Matrix4().makeRotationFromEuler(new THREE.Euler(xr + extra[0], yr + extra[1], zr + extra[2], 'ZYX')))
    .multiply(new THREE.Matrix4().makeScale(xs, ys, zs));
  const normalMatrix = new THREE.Matrix3().getNormalMatrix(m);

  for (const cube of part.cubes) {
    const center = new THREE.Vector3();
    let n = 0;
    for (const poly of cube) for (let i = 0; i < 20; i += 5) center.add(new THREE.Vector3(poly[i], poly[i + 1], poly[i + 2])), n++;
    center.divideScalar(n || 1);

    for (const poly of cube) {
      const local = [0, 5, 10, 15].map((i) => new THREE.Vector3(poly[i], poly[i + 1], poly[i + 2]));
      const normal = new THREE.Vector3().subVectors(local[1], local[0]).cross(new THREE.Vector3().subVectors(local[2], local[0]));
      if (normal.lengthSq() === 0) continue; // zero-thickness face (e.g. flat planes seen edge-on)
      const faceCenter = local.reduce((a, v) => a.add(v), new THREE.Vector3()).divideScalar(4);
      if (normal.dot(faceCenter.sub(center)) < 0) normal.negate();
      visit({
        part: name,
        verts: local.map((v) => v.applyMatrix4(m).toArray() as Vec3),
        uvs: [0, 5, 10, 15].map((i) => [poly[i + 3], poly[i + 4]] as [number, number]),
        normal: normal.applyMatrix3(normalMatrix).normalize(),
      });
    }
  }
  for (const [child, p] of Object.entries(part.children)) walk(p, m, name ? `${name}/${child}` : child, look, visit);
}

/** Directional shading Minecraft-style: top 1.0, bottom 0.5, north/south 0.8, east/west 0.6. */
function shade(n: THREE.Vector3): number {
  return Math.min(1, n.x * n.x * 0.6 + n.y * n.y * ((3 + n.y) / 4) + n.z * n.z * 0.8);
}

export interface LayerSpec {
  model: string;
  texture: string;
  tint?: number;
  emissive?: boolean;
  /** Only draw this child part (and its children). */
  part?: string;
  /** Overrides for the root part's pose, as a model's setupAnim would set them. */
  rootPose?: Partial<Record<(typeof POSE_FIELDS)[number], number>>;
}

const POSE_FIELDS = ['x', 'y', 'z', 'xRot', 'yRot', 'zRot'] as const;

function withRootPose(root: PartJson, override: LayerSpec['rootPose']): PartJson {
  if (!override) return root;
  const pose = [...root.pose];
  POSE_FIELDS.forEach((f, i) => {
    if (override[f] !== undefined) pose[i] = override[f]!;
  });
  return { ...root, pose };
}

/**
 * Mesh for one model layer in its own (pixel) space. `outer` is the transform the mesh will be
 * placed under; shading is computed for normals as they end up after it, like in game.
 */
export async function buildLayerMesh(
  store: AssetStore,
  layer: LayerSpec,
  index: number,
  outer: THREE.Matrix4,
  look?: MobLook,
): Promise<THREE.Mesh | undefined> {
  const model = ENTITY_MODELS[layer.model];
  if (!model) return undefined;
  const tex = await loadTexture(store, layer.texture);
  const outerNormal = new THREE.Matrix3().getNormalMatrix(outer);
  const inPart = (name: string) => !layer.part || name === layer.part || name.startsWith(`${layer.part}/`);
  /** Geometry of the layer in a pose; the same parts in the same order every time. */
  const geometry = (pose: MobLook | undefined) => {
    const batch = new MeshBatch();
    const parts: string[] = [];
    walk(withRootPose(model.root, layer.rootPose), new THREE.Matrix4(), '', pose, ({ part, verts, uvs, normal }) => {
      if (!inPart(part)) return;
      parts.push(part);
      const s = layer.emissive ? 1 : shade(normal.clone().applyMatrix3(outerNormal).normalize());
      // Minecraft's quad order (0,1,2,3) is the reverse of MeshBatch's corner order.
      const order = [0, 3, 2, 1];
      batch.quad(
        order.map((i) => verts[i]),
        order.map((i) => [uvs[i][0], 1 - uvs[i][1]] as [number, number]),
        vertexColor(s, layer.tint ?? 0xffffff),
      );
    });
    return { batch, parts };
  };
  const { batch, parts } = geometry(look);
  // the game draws cutout entity textures without culling, so flat parts show from both sides (tadpole tail)
  const side = tex.translucent || layer.emissive ? THREE.FrontSide : THREE.DoubleSide;
  const mesh = batch.toMesh(tex, side, index);
  if (layer.emissive) {
    const mat = mesh.material as THREE.MeshBasicMaterial;
    mat.blending = THREE.AdditiveBlending;
    mat.transparent = true;
    mat.depthWrite = false;
  }
  mesh.renderOrder = index;
  const picking: LayerPicking = { layer: index, tex, parts };
  mesh.userData.picking = picking;
  // animation: rewrite the vertices in place for another pose
  const repose: Repose = (pose) => {
    const next = geometry(pose).batch;
    const position = mesh.geometry.getAttribute('position') as THREE.BufferAttribute;
    const color = mesh.geometry.getAttribute('color') as THREE.BufferAttribute;
    if (next.pos.length !== position.array.length) return;
    (position.array as Float32Array).set(next.pos);
    (color.array as Float32Array).set(next.col);
    position.needsUpdate = true;
    color.needsUpdate = true;
    mesh.geometry.computeBoundingSphere();
  };
  mesh.userData.repose = repose;
  return mesh;
}

type Repose = (look: MobLook) => void;

/** Leaf names of every part of a model layer (for animations). */
function partNames(modelKey: string): string[] {
  const out: string[] = [];
  const visit = (p: PartJson) => {
    for (const [name, child] of Object.entries(p.children)) {
      out.push(name);
      visit(child);
    }
  };
  const m = ENTITY_MODELS[modelKey];
  if (m) visit(m.root);
  return out;
}

/** What a layer mesh keeps for finding the texture pixel under a click. */
interface LayerPicking {
  layer: number;
  tex: TexInfo;
  /** Model part of each quad (two triangles per quad, in order). */
  parts: string[];
}

/** The texture pixel a click landed on. */
export interface TexturePick {
  /** Index into the mob's layers. */
  layer: number;
  part: string;
  /** Position in the texture, 0–1 from the top left. */
  u: number;
  v: number;
  /** Pixel in the texture as loaded (may be higher resolution than the model's texture size). */
  x: number;
  y: number;
  width: number;
  height: number;
  /** Where the click landed, in world space. */
  point: [number, number, number];
}

/**
 * The visible texture pixel under a click on a mob built by `buildMobObject`. Transparent pixels
 * are skipped so a click goes through the empty parts of overlay layers; of layers drawn on the
 * same surface (spider eyes), the one on top wins.
 */
export function pickTexture(hits: THREE.Intersection[]): TexturePick | undefined {
  const picks: (TexturePick & { distance: number })[] = [];
  for (const hit of hits) {
    const picking = hit.object.userData.picking as LayerPicking | undefined;
    if (!picking || !hit.uv || hit.faceIndex == null) continue;
    const { tex } = picking;
    const u = THREE.MathUtils.clamp(hit.uv.x, 0, 0.9999);
    const v = THREE.MathUtils.clamp(1 - hit.uv.y, 0, 0.9999);
    const x = Math.floor(u * tex.width);
    const y = Math.floor(v * tex.height);
    if (tex.pixels[(y * tex.width + x) * 4 + 3] === 0) continue;
    const part = picking.parts[Math.floor(hit.faceIndex / 2)] ?? '';
    const point = hit.point.toArray() as [number, number, number];
    picks.push({ layer: picking.layer, part, u, v, x, y, width: tex.width, height: tex.height, point, distance: hit.distance });
  }
  if (picks.length === 0) return undefined;
  const nearest = Math.min(...picks.map((p) => p.distance));
  const { distance: _, ...pick } = picks
    .filter((p) => p.distance - nearest < 1e-3)
    .reduce((a, b) => (b.layer > a.layer ? b : a));
  return pick;
}

/** Entity space is y-down with the feet at y = 24 and the face towards -z. */
const MOB_ROOT = new THREE.Matrix4().makeTranslation(0, 1.5, 0).multiply(new THREE.Matrix4().makeScale(1 / 16, -1 / 16, -1 / 16));

/** Layer space of the game's render layers: blocks instead of pixels, same axes as the model. */
const LAYER_SPACE = new THREE.Matrix4().makeTranslation(0, 1.5, 0).multiply(new THREE.Matrix4().makeScale(1, -1, -1));
const deg = (d: number) => (d * Math.PI) / 180;
const rotY = (d: number) => new THREE.Matrix4().makeRotationY(deg(d));
const move = (x: number, y: number, z: number) => new THREE.Matrix4().makeTranslation(x, y, z);
const FLIP = new THREE.Matrix4().makeScale(-1, -1, 1);

/**
 * A mooshroom's mushrooms, placed like the game's MushroomCowMushroomLayer: two on the back, one
 * on the head (which follows the head when it turns). Block models are centred on the origin, so
 * the game's translate(-0.5) before drawing the block is already done.
 */
async function buildMushrooms(store: AssetStore, mob: MobDef, mainModel: string) {
  const id = `minecraft:block/${mob.variant === 'brown' ? 'brown' : 'red'}_mushroom`;
  const block = () => buildModelObject(store, { ref: { model: id, tints: [] }, model: resolveModel(store, id) }, 'none');
  const place = (obj: THREE.Object3D, m: THREE.Matrix4) => {
    obj.matrixAutoUpdate = false;
    obj.matrix.copy(LAYER_SPACE.clone().multiply(m));
  };
  const group = new THREE.Group();
  const back = move(0.2, -0.35, 0.5);
  const one = await block();
  place(one, back.clone().multiply(rotY(-48)).multiply(FLIP));
  const two = await block();
  place(two, back.clone().multiply(rotY(42)).multiply(move(0.1, 0, -0.6)).multiply(rotY(-48)).multiply(FLIP));
  const onHead = await block();
  const head = ENTITY_MODELS[mainModel]?.root.children.head;
  const headAt = (extra: [number, number, number] = [0, 0, 0]) => {
    const [x, y, z, xr, yr, zr] = head?.pose ?? [0, 0, 0, 0, 0, 0];
    const m = move(x / 16, y / 16, z / 16).multiply(new THREE.Matrix4().makeRotationFromEuler(new THREE.Euler(xr + extra[0], yr + extra[1], zr + extra[2], 'ZYX')));
    place(onHead, m.multiply(move(0, -0.7, -0.2)).multiply(rotY(-78)).multiply(FLIP));
  };
  headAt();
  group.add(one, two, onHead);
  return { group, follow: (pose: Record<string, [number, number, number]>) => headAt(pose.head) };
}

/** Animates a mob built by `buildMobObject` (`ticks` at 20 per second). */
export type MobAnimator = (ticks: number, motion: Motion) => void;

export async function buildMobObject(store: AssetStore, mob: MobDef, options?: MobOptions): Promise<THREE.Group> {
  // Flip into world space so the mob stands on y = 0 looking at +z.
  const root = new THREE.Group();
  root.matrixAutoUpdate = false;
  root.matrix.copy(MOB_ROOT);
  const layers = mobLayers(store, mob, options);
  const reposers: Repose[] = [];
  for (let li = 0; li < layers.length; li++) {
    const mesh = await buildLayerMesh(store, layers[li], li, MOB_ROOT, mob);
    if (!mesh) continue;
    root.add(mesh);
    reposers.push(mesh.userData.repose);
  }
  const wrapper = new THREE.Group();
  wrapper.add(root);
  // mooshrooms carry their mushrooms unless they were sheared
  const mushrooms = options?.mushrooms !== false && mob.entity === 'mooshroom' && !mob.babyOf ? await buildMushrooms(store, mob, mob.layers[0].model) : undefined;
  if (mushrooms) wrapper.add(mushrooms.group);
  const names = [...new Set(layers.flatMap((l) => partNames(l.model)))];
  let resting = true;
  const animate: MobAnimator = (ticks, motion) => {
    // standing still needs one update back to the resting pose, not one per frame
    if (motion === 'still' && resting) return;
    resting = motion === 'still';
    const moving = motionPose(names, ticks, motion);
    const pose = mergePoses(mob.pose, moving);
    for (const r of reposers) r({ pose, hidden: mob.hidden });
    mushrooms?.follow(moving);
  };
  wrapper.userData.animate = animate;
  return wrapper;
}

export interface UVRect {
  part: string;
  /** Which way the face looks on the standing mob. */
  face: FaceDir;
  x0: number;
  y0: number;
  x1: number;
  y1: number;
}

/** The direction a normal in entity model space (y down, z towards the back) looks in the world. */
function facing(n: THREE.Vector3): FaceDir {
  const [x, y, z] = [Math.abs(n.x), Math.abs(n.y), Math.abs(n.z)];
  if (y >= x && y >= z) return n.y < 0 ? 'up' : 'down';
  if (x >= z) return n.x > 0 ? 'east' : 'west';
  return n.z > 0 ? 'north' : 'south';
}

/** Texture regions (in the model's texture pixel space) used by each face, for the UV overlay. */
export function layerUVRects(modelKey: string): { tex: [number, number]; rects: UVRect[] } | undefined {
  const model = ENTITY_MODELS[modelKey];
  if (!model) return undefined;
  const [w, h] = model.tex;
  const rects: UVRect[] = [];
  walk(model.root, new THREE.Matrix4(), '', undefined, ({ part, uvs, normal }) => {
    const us = uvs.map((u) => u[0] * w);
    const vs = uvs.map((u) => u[1] * h);
    // some vanilla models reach past their texture (a baby llama's chests)
    const r = { part, face: facing(normal), x0: Math.max(0, Math.min(...us)), y0: Math.max(0, Math.min(...vs)), x1: Math.min(w, Math.max(...us)), y1: Math.min(h, Math.max(...vs)) };
    if (r.x1 > r.x0 && r.y1 > r.y0) rects.push(r);
  });
  return { tex: model.tex, rects };
}

/** The faces of a mob model on its texture, for a UV template. */
export function entityTemplate(modelKey: string): UVTemplate | undefined {
  const data = layerUVRects(modelKey);
  return data && { size: data.tex, faces: data.rects };
}

/** Files a mob's appearance depends on (with `options`, its equipment too); used for source badges and cache keys. */
export function mobDeps(mob: MobDef, store?: AssetStore, options?: MobOptions): string[] {
  const layers = store && options ? mobLayers(store, mob, options) : mob.layers;
  const files = layers.flatMap((l) => [texturePath(l.texture), `${texturePath(l.texture)}.mcmeta`]);
  if (store && options) files.push(...store.list('assets/').filter((p) => /^assets\/[^/]+\/equipment\//.test(p)));
  return [...new Set(files)];
}
